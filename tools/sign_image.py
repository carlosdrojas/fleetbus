#!/usr/bin/env python3
"""FleetBus image signing (Ed25519 via PyNaCl). Layout must match firmware/common/image.h:

  0x00 magic 'FBIM' u32 | 0x04 hw_id u16 | 0x06 slot u8 | 0x07 hdr_version u8 | 0x08 version u32 | 0x0C size u32
  0x10 node_id u8 | 0x20 sha512[64] | 0x60 signature[64] (over bytes 0x00..0x5F) | header padded to 0x200 with 0xFF

The private key lives in ~/.fleetbus/keys and never in the repo; only the public key (firmware/keys/fleetbus_pub.h) is committed.

  sign_image.py keygen [--name dev] [--force]
  sign_image.py sign   app.bin --node battery --slot 0 --version 3 [--key ~/.fleetbus/keys/dev.key] [-o out.signed]
  sign_image.py info   out.signed
"""
from __future__ import annotations

import argparse
import hashlib
import os
import stat
import struct
import sys
from pathlib import Path

from nacl.signing import SigningKey, VerifyKey

ROOT = Path(__file__).resolve().parent.parent
KEYDIR = Path(os.environ.get("FLEETBUS_KEYDIR", Path.home() / ".fleetbus" / "keys"))
PUB_HEADER = ROOT / "firmware" / "keys" / "fleetbus_pub.h"
MAGIC = 0x4D494246
HW_G431 = 0x4301
HDR_SIZE = 0x200
SIGNED_LEN = 0x60
SLOT_SIZE = 48 * 1024
NODES = {"battery": 1, "body": 2, "telematics": 3}

def build_image(body: bytes, node: int, slot: int, version: int, key: SigningKey, hw_id: int = HW_G431) -> bytes:
    if len(body) == 0 or len(body) > SLOT_SIZE - HDR_SIZE:
        raise SystemExit(f"image body {len(body)} B does not fit a slot ({SLOT_SIZE - HDR_SIZE} B max)")
    h = bytearray(b"\xff" * HDR_SIZE)
    h[0:0x20] = struct.pack("<IHBBII", MAGIC, hw_id, slot, 1, version, len(body)) + bytes([node]) + b"\x00" * 15
    h[0x20:0x60] = hashlib.sha512(body).digest()
    h[0x60:0xA0] = key.sign(bytes(h[:SIGNED_LEN])).signature
    return bytes(h) + body

def parse_header(blob: bytes) -> dict:
    magic, hw, slot, hv, version, size = struct.unpack_from("<IHBBII", blob)
    return {"magic_ok": magic == MAGIC, "hw_id": hw, "slot": slot, "hdr_version": hv, "version": version, "size": size,
            "node": blob[0x10], "sha512": blob[0x20:0x60].hex(), "sig": blob[0x60:0xA0].hex()}

def verify_image(blob: bytes, pub: VerifyKey) -> None:
    h = parse_header(blob)
    pub.verify(blob[:SIGNED_LEN], blob[0x60:0xA0])
    if hashlib.sha512(blob[HDR_SIZE:HDR_SIZE + h["size"]]).digest() != blob[0x20:0x60]:
        raise ValueError("body hash mismatch")

def load_key(path: Path) -> SigningKey:
    return SigningKey(bytes.fromhex(path.read_text().strip()))

def cmd_keygen(a) -> int:
    KEYDIR.mkdir(parents=True, exist_ok=True)
    kp = KEYDIR / f"{a.name}.key"
    if kp.exists() and not a.force:
        print(f"{kp} exists; use --force to replace (this invalidates every image signed with it)", file=sys.stderr)
        return 1
    sk = SigningKey.generate()
    kp.write_text(sk.encode().hex() + "\n")
    kp.chmod(stat.S_IRUSR | stat.S_IWUSR)
    pub = bytes(sk.verify_key)
    PUB_HEADER.parent.mkdir(parents=True, exist_ok=True)
    PUB_HEADER.write_text("/* Public verification key (Ed25519). Generated by tools/sign_image.py keygen. The private half is NOT in the repo. */\n"
                          "#pragma once\n#include <stdint.h>\nstatic const uint8_t FB_PUBKEY[32] = {\n    "
                          + ", ".join(f"0x{b:02x}" for b in pub) + "\n};\n")
    print(f"private key: {kp} (keep it out of git)\npublic key:  {PUB_HEADER}\nfingerprint: {pub[:6].hex()}")
    return 0

def cmd_sign(a) -> int:
    body = Path(a.bin).read_bytes()
    key = load_key(Path(a.key).expanduser())
    blob = build_image(body, NODES[a.node], a.slot, a.version, key)
    out = Path(a.out) if a.out else Path(a.bin).with_suffix(f".v{a.version}.signed")
    out.write_bytes(blob)
    print(f"{out}: node={a.node} slot={a.slot} version={a.version} body={len(body)} B total={len(blob)} B")
    return 0

def cmd_info(a) -> int:
    blob = Path(a.file).read_bytes()
    for k, v in parse_header(blob).items():
        print(f"{k:12} {v}")
    return 0

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    k = sub.add_parser("keygen"); k.add_argument("--name", default="dev"); k.add_argument("--force", action="store_true"); k.set_defaults(fn=cmd_keygen)
    s = sub.add_parser("sign"); s.add_argument("bin"); s.add_argument("--node", choices=NODES, required=True)
    s.add_argument("--slot", type=int, choices=(0, 1), required=True); s.add_argument("--version", type=int, required=True)
    s.add_argument("--key", default=str(KEYDIR / "dev.key")); s.add_argument("-o", "--out"); s.set_defaults(fn=cmd_sign)
    i = sub.add_parser("info"); i.add_argument("file"); i.set_defaults(fn=cmd_info)
    a = ap.parse_args()
    return a.fn(a)

if __name__ == "__main__":
    sys.exit(main())
