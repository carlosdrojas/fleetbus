#!/usr/bin/env python3
"""Regenerate protocol/can_vectors.json from can/fleetbus.dbc via cantools. The Go decoder (backend/internal/canmsg)
and the C codegen must agree with these; review diffs."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "gateway"))
from fleetbus import canmsg  # noqa: E402

CASES = {
    "Heartbeat": [dict(NodeId=2, FwVersion=3, UptimeS=70000, State=1, Slot=1, Trial=1, ProtoVer=1),
                  dict(NodeId=1, FwVersion=65535, UptimeS=16777215, State=6, Slot=0, Trial=0, ProtoVer=1)],
    "BatteryStatus": [dict(PackMilliVolt=3800, CurrentMilliAmp=-1500, TempDeciC=-50, SocPct=66, ProtoVer=1),
                      dict(PackMilliVolt=65535, CurrentMilliAmp=32767, TempDeciC=32767, SocPct=100, ProtoVer=1)],
    "BodyStatus": [dict(Lights=3, ServoDeg=45, LimpHome=0, ProtoVer=1), dict(Lights=4, ServoDeg=90, LimpHome=1, ProtoVer=1)],
    "FaultEvent": [dict(FaultCode=0x10, Severity=2, NodeId=1, ProtoVer=1)],
    "OtaAck": [dict(NextBlock=586, Status=3, NodeId=2, ProtoVer=1)],
    "VehicleObd": [dict(SpeedKph=88, RpmQuarter=11200, CoolantC=130, ProtoVer=1)],
}
out = []
for name, cases in CASES.items():
    m = canmsg.msg(name)
    for sig in cases:
        out.append({"message": name, "id": m.frame_id, "dlc": m.length, "data_hex": bytes(m.encode(sig, strict=True)).hex(), "signals": sig})
(ROOT / "protocol" / "can_vectors.json").write_text(json.dumps({"_note": "Generated by tools/gen_can_vectors.py", "vectors": out}, indent=2) + "\n")
print(f"wrote {len(out)} CAN vectors")
