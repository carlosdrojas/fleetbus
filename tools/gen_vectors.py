#!/usr/bin/env python3
"""Regenerate protocol/golden_vectors.json. Review the diff: the vectors are the cross-language contract."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "gateway"))
from fleetbus import fbp  # noqa: E402

def vec(name, ptype, src, seq, payload, flags=0, **fields):
    wire = fbp.encode(fbp.Packet(ptype, src, seq, payload, flags))
    return {"name": name, "type": ptype, "src": src, "seq": seq, "flags": flags,
            "payload_hex": payload.hex(), "wire_hex": wire.hex(), "fields": fields}

recs = [fbp.CanRecord(0, 0x100, bytes([2, 1, 0x02, 0x01, 0x70, 0x11, 0x01, 1, 0])[:8]),
        fbp.CanRecord(100, 0x200, bytes([0x74, 0x0E, 0x18, 0xFC, 0xCE, 0xFF, 0x50, 1])),
        fbp.CanRecord(150, 0x80000123, b"")]

good = [
    vec("ack_zero", fbp.ACK, 0, 1, fbp.enc_ack(0)),
    vec("telemetry_three_records", fbp.TELEMETRY, 7, 42, fbp.enc_telemetry(1760000000123, recs), base_ts_ms=1760000000123,
        records=[{"dt_ms": r.dt_ms, "can_id": r.can_id, "data_hex": r.data.hex()} for r in recs]),
    vec("gateway_heartbeat", fbp.HEARTBEAT, 7, 43, fbp.enc_heartbeat(3600, 12, 0, 5), uptime_s=3600, unacked=12, spooled=0, resent=5),
    vec("ack_cumulative", fbp.ACK, 0, 9, fbp.enc_ack(41), cum_ack=41),
    vec("nack_two_gaps", fbp.NACK, 0, 10, fbp.enc_nack([44, 47]), seqs=[44, 47]),
    vec("ota_offer", fbp.OTA_OFFER, 0, 11, fbp.enc_ota_offer(2, 1, 3, 20480, 77), node=2, slot=1, version=3, size=20480, image_id=77),
    vec("ota_chunk_retransmit", fbp.OTA_CHUNK, 0, 12, fbp.enc_ota_chunk(2, 6000, bytes(range(16))), flags=1, node=2, offset=6000, data_hex=bytes(range(16)).hex()),
    vec("ota_status_confirmed", fbp.OTA_STATUS, 7, 44, fbp.enc_ota_status(2, fbp.OTA_CONFIRMED, 20480, 0), node=2, status=5, next_offset=20480, detail=0),
    vec("max_seq", fbp.ACK, 255, 0xFFFFFFFF, fbp.enc_ack(0xFFFFFFFE), cum_ack=0xFFFFFFFE),
]

def corrupt(name, wire: bytes, why: str):
    return {"name": name, "wire_hex": wire.hex(), "why": why}

base = bytes.fromhex(good[3]["wire_hex"])
bad = [
    corrupt("bad_crc", base[:-1] + bytes([base[-1] ^ 1]), "last CRC byte flipped"),
    corrupt("bad_magic", b"\x00" + base[1:], "magic[0] wrong"),
    corrupt("bad_version", base[:2] + b"\x02" + base[3:], "version 2"),
    corrupt("truncated", base[:-3], "short datagram"),
    corrupt("trailing_garbage", base + b"\x00", "length mismatch"),
    corrupt("empty", b"", "no bytes"),
]
# header-valid packets (correct CRC) that are semantically illegal
def with_crc(head: bytes) -> bytes:
    import struct
    return head + struct.pack("<I", fbp.crc32c(head))
hdr = fbp.HEADER
bad.append(corrupt("reserved_flag_set", with_crc(hdr.pack(fbp.MAGIC, 1, fbp.ACK, 0, 0x80, 1, 4) + fbp.enc_ack(1)), "flag bit7 set with valid crc"))
bad.append(corrupt("unknown_type", with_crc(hdr.pack(fbp.MAGIC, 1, 99, 0, 0, 1, 4) + fbp.enc_ack(1)), "type 99 with valid crc"))

# Golden signed image (fixed key + body) that the Python signer, the C verifier and the Go verifier must all accept.
from nacl.signing import SigningKey  # noqa: E402
from fleetbus import image as _img  # noqa: E402
_key = SigningKey(bytes(range(32)))
_body = bytes((i * 11 + 5) & 0xFF for i in range(700))
golden_image = {"pubkey_hex": bytes(_key.verify_key).hex(), "node": 2, "slot": 1, "version": 9,
                "blob_hex": _img.build_image(_body, 2, 1, 9, _key).hex()}

out = {"_note": "Generated by tools/gen_vectors.py. CRC-32C of '123456789' must be 0xE3069283.", "crc32c_check": {"input": "123456789", "crc": 3808858755},
       "valid": good, "invalid": bad, "golden_image": golden_image}
(ROOT / "protocol" / "golden_vectors.json").write_text(json.dumps(out, indent=2) + "\n")
print(f"wrote {len(good)} valid + {len(bad)} invalid vectors + 1 golden image")
